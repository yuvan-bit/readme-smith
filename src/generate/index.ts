import path from 'node:path';
import type { GenerateOptions, Lang, ProjectProfile, SectionId } from '../types.js';
import type { ProviderId } from '../i18n/provider.js';
import { makeT } from '../i18n/dict.js';
import { detectLanguage, selectProvider, translateMarkdown } from '../i18n/index.js';
import { buildToc, heading, joinBlocks, normalizeDocument } from './markdown.js';
import { SECTION_IDS, TOC_SENTINEL, makeContext, renderSections } from './sections.js';

export interface RenderedReadme {
  lang: Lang;
  /** File name relative to the project root. */
  filename: string;
  content: string;
}

export const LOCALE_FILENAME: Record<Lang, string> = {
  en: 'README.md',
  zh: 'README.zh-CN.md',
};

export const LOCALE_NAME: Record<Lang, string> = { en: 'English', zh: '简体中文' };

/** Every section this generator can render is on by default; `SECTION_IDS` order is canonical. */
export const DEFAULT_SECTIONS: SectionId[] = [...SECTION_IDS];

export function defaultOptions(root: string): GenerateOptions {
  return {
    root: path.resolve(root),
    langs: ['en', 'zh'],
    separateFiles: true,
    sections: DEFAULT_SECTIONS,
    badges: true,
    diagrams: true,
    badgeStyle: 'flat-square',
    maxTreeDepth: 3,
    overwrite: false,
    translateProse: false,
    allowRegistryClaims: true,
    sectionOverrides: {},
    includeLanguageSwitcher: true,
    toc: true,
    tocMaxDepth: 2,
  };
}

/**
 * Footer appended to every generated README.
 *
 * Deliberately no date: a run-date stamp makes the output depend on when the
 * tool ran rather than what the repository contains, so a README generated on
 * Monday would report drift on Tuesday and `generate --check` could never be
 * trusted in CI. "When did this change?" is git log's question, not the
 * document's.
 */
function renderFooter(profile: ProjectProfile, lang: Lang): string {
  const t = makeT(lang);
  const starPrompt = profile.repo.slug && profile.repo.host === 'github' ? t('meta.starPrompt') : '';
  const generated = lang === 'zh'
    ? '由 **readme-smith** 根据仓库内容自动生成'
    : 'Generated by **readme-smith** from the repository contents';

  return joinBlocks([
    starPrompt ? `> ${starPrompt}` : '',
    '<hr />',
    `<p align="center">${generated}</p>`,
  ]);
}

/** Render the complete README for one language. */
export function renderReadme(profile: ProjectProfile, lang: Lang, options: GenerateOptions): string {
  const t = makeT(lang);
  const ctx = makeContext(profile, lang, options.langs, t, options);

  const body = renderSections(ctx);

  // Second pass: the TOC can only be built from headings that now exist.
  let document = body;
  if (body.includes(TOC_SENTINEL)) {
    const withoutSentinel = body.replace(TOC_SENTINEL, '');
    const toc = buildToc(withoutSentinel, options.tocMaxDepth, t('section.tableOfContents'));
    const tocBlock = toc ? `${heading(2, t('section.tableOfContents'))}\n\n${toc}` : '';
    document = body.replace(TOC_SENTINEL, tocBlock);
  }

  const autoWarning = options.translateProse || profile.warnings.length > 0
    ? `> _${t('meta.autoGeneratedWarning')}_`
    : '';

  return normalizeDocument(joinBlocks([document, renderFooter(profile, lang), autoWarning]));
}

/** Render every requested language into its own file descriptor. */
export async function generateReadmes(
  profile: ProjectProfile,
  options: GenerateOptions,
): Promise<RenderedReadme[]> {
  const rendered: RenderedReadme[] = [];
  for (const lang of options.langs) {
    const localized = await localizeProse(profile, lang, options, options.provider);
    rendered.push({ lang, filename: LOCALE_FILENAME[lang], content: renderReadme(localized, lang, options) });
  }
  return rendered;
}

/**
 * Translate the project-specific prose for one language.
 *
 * Section headings, notes and labels never need a provider — they come from
 * the bilingual dictionary. The manifest description is the exception: it is
 * the author's own sentence and exists in exactly one language. Without this
 * step a Chinese README carries an English tagline, which is the specific
 * half-translated look the tool is supposed to avoid.
 *
 * Caveats are appended to `profile.warnings`, which is the report channel the
 * CLI prints at the end — a provider that quietly fell back to a free public
 * endpoint has to say so on the headline sentence.
 */
async function localizeProse(
  profile: ProjectProfile,
  lang: Lang,
  options: GenerateOptions,
  providerPreference?: ProviderId,
): Promise<ProjectProfile> {
  if (!options.translateProse) return profile;

  const description = profile.description?.trim();
  if (!description) return profile;
  if (detectLanguage(description) === lang) return profile;

  const selected = selectProvider(providerPreference);
  if (!selected) {
    warn(profile, providerPreference === 'none'
      ? `--translate-prose was requested with --provider none, so the ${LOCALE_NAME[lang]} tagline keeps the original wording.`
      : `--translate-prose was requested but no translation provider is configured; the ${LOCALE_NAME[lang]} tagline keeps its original wording.`);
    return profile;
  }

  const result = await translateMarkdown(description, {
    from: 'auto', to: lang, provider: selected.provider.id, concurrency: 4,
  });
  if (result.provider === 'none' || result.segmentsTranslated === 0) {
    warn(profile, `The ${selected.provider.id} provider returned nothing for the project description; it was left as written.`);
    return profile;
  }
  for (const caveat of result.warnings) warn(profile, caveat);
  return { ...profile, description: result.text.trim() };
}

function warn(profile: ProjectProfile, message: string): void {
  profile.warnings.push(message);
}

export { SECTION_IDS };
export type { GenerateOptions };
