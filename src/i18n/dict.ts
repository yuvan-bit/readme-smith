export const DICTS: Record<'en' | 'zh', Dict> = { en: EN, zh: ZH };

/** Translate a key, substituting `{name}` style placeholders. */
export function translate(lang: 'en' | 'zh', key: DictKey, vars: Record<string, string | number> = {}): string {
  const template = DICTS[lang][key];
  if (Object.keys(vars).length === 0) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** A bound translator for one language — reads better at call sites. */
export function makeT(lang: 'en' | 'zh'): (key: DictKey, vars?: Record<string, string | number>) => string {
  return (key, vars) => translate(lang, key, vars);
}

export type T = ReturnType<typeof makeT>;
